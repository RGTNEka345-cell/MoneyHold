import React from 'react';
import {render,screen,fireEvent,act} from '@testing-library/react';
import {MemoryRouter,Routes,Route} from 'react-router-dom';
import Orders from './Orders';
import SellerOrders from '../../seller/Orders/SellerOrders';
import {customerRequest} from '../../../services/customerApi';
import {sellerRequest} from '../../../services/sellerApi';
jest.mock('../../../services/customerApi',()=>({customerRequest:jest.fn()}));
jest.mock('../../../services/sellerApi',()=>({sellerRequest:jest.fn()}));
jest.mock('../../../components/HomePage/Navbar',()=>()=>null);
jest.mock('../../../components/HomePage/Footer',()=>()=>null);
jest.mock('../../../components/Theme/ThemeToggle',()=>()=>null);
jest.mock('../../../components/Shared/NotificationBell',()=>()=>null);
jest.mock('../../../components/Customer/OrderDetails',()=>({order})=><p>Details for {order.order_number}</p>);
const order={id:7,order_number:'MH-TEST',status:'placed',total_cents:10000,created_at:'2026-10-19T10:00:00Z'};
beforeEach(()=>{global.EventSource=jest.fn().mockImplementation(()=>({close:jest.fn()}));});
test.each([false,true])('detail → all orders → detail is safe while new data is loading (seller=%s)',async seller=>{
  const request=seller?sellerRequest:customerRequest;
  let finishList,finishDetail;
  request.mockResolvedValueOnce({order}).mockImplementationOnce(()=>new Promise(resolve=>{finishList=resolve;})).mockImplementationOnce(()=>new Promise(resolve=>{finishDetail=resolve;}));
  const prefix=seller?'/seller':'/customer';
  render(<MemoryRouter initialEntries={[prefix+'/orders/7']} future={{v7_startTransition:true,v7_relativeSplatPath:true}}><Routes><Route path={prefix+'/orders/:id?'} element={seller?<SellerOrders/>:<Orders/>}/></Routes></MemoryRouter>);
  await screen.findByText('Details for MH-TEST');
  fireEvent.click(screen.getByRole('link',{name:/All orders/}));
  expect(screen.getByRole('status').textContent).toContain('Loading orders');
  await act(async()=>finishList({orders:[order],page:1,pages:1}));
  fireEvent.click(screen.getByRole('link',{name:/MH-TEST/}));
  expect(screen.getByRole('status').textContent).toContain('Loading orders');
  await act(async()=>finishDetail({order}));
  await screen.findByText('Details for MH-TEST');
});
