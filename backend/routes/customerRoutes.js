
const router=require('express').Router();
const {rateLimit}=require('express-rate-limit');
const controller=require('../controllers/CustomerController');
router.use(require('../middlewares/customerOrigin'));
const reset=require('../controllers/PasswordResetController');
const resetLimiter=()=>rateLimit({windowMs:15*60000,limit:10,standardHeaders:true,legacyHeaders:false,message:{message:'Too many reset attempts. Please try again in 15 minutes.'}});
router.post('/forgot-password',resetLimiter(),reset.forgot);
router.post('/reset-password',resetLimiter(),reset.reset);
router.post('/login',rateLimit({windowMs:15*60000,limit:10,standardHeaders:true,legacyHeaders:false,message:{message:'Too many login attempts. Please try again in 15 minutes.'}}),controller.login);
router.get('/me',require('../middlewares/customerAuth'),controller.me);
router.post('/logout',controller.logout);
router.use('/cart',require('./cartRoutes'));
router.use('/orders',require('./orderRoutes'));
router.use('/notifications',require('../middlewares/customerAuth'),require('./notificationRoutes'));
const profile=require('../controllers/CustomerProfileController');
router.use(require('../middlewares/customerAuth'));
const engagement=require('../controllers/EngagementController');
router.get('/wishlist',engagement.wishlist);
router.put('/wishlist/:id',engagement.saveWishlist);
router.delete('/wishlist/:id',engagement.removeWishlist);
router.get('/reviews/:id',engagement.mine);
router.put('/reviews/:id',rateLimit({windowMs:60000,limit:20}),engagement.changeReview);
router.delete('/reviews/:id',engagement.changeReview);
router.get('/profile',profile.profile);
router.get('/profile/events',profile.stream);
router.patch('/profile',profile.update);
router.get('/addresses',profile.addresses);
router.post('/addresses',profile.addressChange('create'));
router.put('/addresses/:id',profile.addressChange('update'));
router.patch('/addresses/:id/default',profile.addressChange('default'));
router.delete('/addresses/:id',profile.addressChange('delete'));
module.exports=router;
