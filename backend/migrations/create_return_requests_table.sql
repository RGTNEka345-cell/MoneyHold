CREATE TABLE IF NOT EXISTS return_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 order_item_id BIGINT UNSIGNED NOT NULL,
 customer_id BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(64) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 kind ENUM('return','exchange') NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 replacement_variant_id BIGINT UNSIGNED NULL,
 replacement_size VARCHAR(20) NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'requested',
 seller_note VARCHAR(1000) NOT NULL DEFAULT '',
 restock_quantity INT UNSIGNED NULL,
 courier_name VARCHAR(100) NULL,
 tracking_number VARCHAR(120) NULL,
 tracking_url VARCHAR(1000) NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY request_once (customer_id,request_key),
 INDEX (order_item_id,status), INDEX (status,created_at),
 FOREIGN KEY (order_id) REFERENCES orders(id),
 FOREIGN KEY (order_item_id) REFERENCES order_items(id),
 FOREIGN KEY (customer_id) REFERENCES customers(id),
 FOREIGN KEY (replacement_variant_id) REFERENCES product_variants(id) ON DELETE SET NULL
) ENGINE=InnoDB;
