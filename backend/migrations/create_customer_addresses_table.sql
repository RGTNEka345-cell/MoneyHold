CREATE TABLE IF NOT EXISTS customer_addresses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 customer_id BIGINT UNSIGNED NOT NULL,
 label VARCHAR(40) NOT NULL,
 recipient_name VARCHAR(120) NOT NULL,
 phone VARCHAR(30) NOT NULL,
 address_line1 VARCHAR(200) NOT NULL,
 address_line2 VARCHAR(200) NOT NULL DEFAULT '',
 city VARCHAR(100) NOT NULL,
 postal_code VARCHAR(20) NOT NULL DEFAULT '',
 country CHAR(2) NOT NULL DEFAULT 'LK',
 is_default BOOLEAN NOT NULL DEFAULT FALSE,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 creation_key VARCHAR(64) NOT NULL,
 creation_hash CHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY customer_creation (customer_id,creation_key),
 INDEX (customer_id,is_default),
 FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE CASCADE
) ENGINE=InnoDB;
